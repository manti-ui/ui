/**
 * Generate the shipped theme presets from the `presets` map in
 * `@manti-ui/tokens`.
 *
 * Two outputs, one source:
 *   - `src/themes/<id>.css` — the preset on `:root`, for whole-app adoption
 *     (`import '@manti-ui/styles/themes/ocean.css'`).
 *   - `src/themes.css` — every preset scoped to `[data-manti-theme='<id>']`,
 *     for a themed section, a gallery, or a preview pane.
 *
 *   node scripts/gen-preset-css.mjs           # rewrite both
 *   node scripts/gen-preset-css.mjs --check    # fail if either is stale
 *
 * A preset is not colors-only. It moves `--manti-cool-hue` and
 * `--manti-radius-factor`, may carry a density, and expands each base color into
 * the full `--variant-*` vocabulary — plus the two branded roles no
 * `[data-variant]` block can reach: `--manti-accent-fill` (Progress spends its
 * `data-variant` slot on linear/circular) and `--manti-selection-*`.
 *
 * The scoped file needs more than the root file. A custom property inherits its
 * *substituted* value, so a role computed on `:root` against the shipped hue
 * cannot re-tint from a nested scope. Every root declaration that transitively
 * reads a moved anchor is therefore re-declared inside the scope, where it
 * resolves locally. The `[data-variant]` blocks need no such treatment: they are
 * declared on the element itself and read whatever the themed ancestor passes
 * down.
 */
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import prettier from 'prettier';

import { readTokensCss } from './lib/tokens-css.mjs';
import { INKS, pickInk } from './lib/variant-ink.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const TOKENS_TS = resolve(here, '../../tokens/src/index.ts');
const TOKENS_CSS = resolve(here, '../src/tokens.css');
const THEMES_DIR = resolve(here, '../src/themes');
const SCOPED_CSS = resolve(here, '../src/themes.css');
const THEMES = ['light', 'dark'];
const check = process.argv.includes('--check');

const t = await import(pathToFileURL(TOKENS_TS).href);
const { root, resolveToken, color } = await readTokensCss(TOKENS_CSS);

const banner = '/* Generated by scripts/gen-preset-css.mjs — DO NOT EDIT. */';
const mix = (base, pct, other) =>
  `color-mix(in oklab, ${base} ${pct}%, ${other})`;
const ld = (light, dark) => `light-dark(${light}, ${dark})`;
const scale = (rem, factor) =>
  `${Number((parseFloat(rem) * factor).toFixed(4))}rem`;

/**
 * Pick `--variant-on-solid` for a base color, per theme, with the same rule the
 * shipped variants go through. The candidate inks are theme-aware, so both are
 * resolved against a scope carrying this preset's neutral hue.
 */
function inkFor(base, scope, label) {
  const picks = {};
  for (const theme of THEMES) {
    const solid = color(base, theme, scope);
    const candidates = [];
    for (const ink of INKS) {
      const c = resolveToken(ink.token, theme, scope);
      if (c.err) fail(`${label}: ${c.err}`);
      candidates.push({ ...ink, c: c.c });
    }
    const { scored, chosen } = pickInk(solid, candidates);
    if (!chosen) {
      const best = scored.reduce((a, b) => (b.ratio > a.ratio ? b : a));
      fail(
        `${label} (${theme}): no ink clears AA on ${base} — best is ` +
          `${best.label} at ${best.ratio.toFixed(2)}:1. Move the color.`,
      );
    }
    picks[theme] = chosen;
  }
  return picks.light.token === picks.dark.token
    ? `var(${picks.light.token})`
    : ld(`var(${picks.light.token})`, `var(${picks.dark.token})`);
}

function fail(message) {
  console.error(`gen-preset-css: ${message}`);
  process.exit(1);
}

/** One base color expanded into the full `--variant-*` vocabulary. */
function variantRoles(base, ink) {
  return [
    ['--variant-solid', base],
    [
      '--variant-solid-hover',
      ld(mix(base, 88, 'white'), mix(base, 88, 'black')),
    ],
    [
      '--variant-solid-active',
      ld(mix(base, 78, 'white'), mix(base, 78, 'black')),
    ],
    ['--variant-on-solid', ink],
    [
      '--variant-soft-bg',
      ld(mix(base, 14, 'white'), mix(base, 22, 'var(--manti-gray-12)')),
    ],
    [
      '--variant-soft-bg-hover',
      ld(mix(base, 22, 'white'), mix(base, 32, 'var(--manti-gray-12)')),
    ],
    [
      '--variant-soft-bg-active',
      ld(mix(base, 30, 'white'), mix(base, 42, 'var(--manti-gray-12)')),
    ],
    ['--variant-soft-text', ld(mix(base, 75, 'black'), mix(base, 42, 'white'))],
    [
      '--variant-border',
      ld(mix(base, 32, 'white'), mix(base, 42, 'var(--manti-gray-11)')),
    ],
    ['--variant-text', ld(mix(base, 78, 'black'), mix(base, 45, 'white'))],
    ['--variant-ring', base],
  ];
}

/** The anchors a preset moves, and the theme values it moves them to. */
function anchors(preset) {
  const out = [
    ['--manti-cool-hue', String(preset.coolHue)],
    ['--manti-radius-factor', preset.radiusFactor],
  ];
  if (preset.density !== 1) {
    out.push(['--manti-space-1', scale(t.space[1], preset.density)]);
    for (const [step, value] of Object.entries(t.controlHeight))
      out.push([
        `--manti-control-height-${step}`,
        scale(value, preset.density),
      ]);
  }
  return out;
}

/** Branded roles that no `[data-variant]` block can reach. */
function brandedRoles(preset, scope) {
  const base = preset.colors.primary;
  if (!base) return [];
  return [
    ['--manti-accent-fill', ld(mix(base, 88, 'black'), base)],
    ['--manti-selection-bg', base],
    [
      '--manti-selection-text',
      inkFor(base, scope, `${preset.label} selection`),
    ],
  ];
}

/**
 * Every root declaration that transitively reads one of `seeds`, in source
 * order. These carry an already-substituted value once inherited, so a scoped
 * preset has to re-declare them to re-resolve against its own anchors.
 */
function dependents(seeds, skip) {
  const set = new Set(seeds);
  for (let grew = true; grew; ) {
    grew = false;
    for (const [name, value] of root) {
      if (set.has(name)) continue;
      const reads = [...set].some((s) =>
        new RegExp(`var\\(\\s*${s}\\s*[,)]`).test(value),
      );
      if (reads) {
        set.add(name);
        grew = true;
      }
    }
  }
  return [...root].filter(
    ([name]) => set.has(name) && !seeds.includes(name) && !skip.includes(name),
  );
}

const block = (selector, declarations, indent = '  ') =>
  [
    `${indent}${selector} {`,
    ...declarations.map(([name, value]) => `${indent}  ${name}: ${value};`),
    `${indent}}`,
  ].join('\n');

const entries = Object.entries(t.presets).filter(([, p]) => !p.default);
const files = new Map();
const scopedBlocks = [];

for (const [id, preset] of entries) {
  const scope = new Map([['--manti-cool-hue', String(preset.coolHue)]]);
  const anchored = anchors(preset);
  const branded = brandedRoles(preset, scope);
  const variantBlocks = Object.entries(preset.colors).map(([variant, base]) => [
    variant,
    variantRoles(base, inkFor(base, scope, `${preset.label} ${variant}`)),
  ]);

  files.set(
    resolve(THEMES_DIR, `${id}.css`),
    [
      banner,
      `/* ${preset.label} — ${preset.description} */`,
      '@layer manti.theme {',
      block(':root', [...anchored, ...branded]),
      ...variantBlocks.map(([variant, roles]) =>
        block(`[data-variant='${variant}']`, roles),
      ),
      '}',
      '',
    ].join('\n'),
  );

  const at = `[data-manti-theme='${id}']`;
  const inherited = dependents(
    anchored.map(([name]) => name),
    branded.map(([name]) => name),
  );
  scopedBlocks.push(
    block(at, [...anchored, ...inherited, ...branded]),
    ...variantBlocks.map(([variant, roles]) =>
      block(
        `${at} [data-variant='${variant}'],\n  ${at}[data-variant='${variant}']`,
        roles,
      ),
    ),
  );
}

files.set(
  SCOPED_CSS,
  [
    banner,
    '/* Every preset scoped to `data-manti-theme`, for pages that show more',
    '   than one theme at a time. Use `themes/<id>.css` for a whole app. */',
    '@layer manti.theme {',
    scopedBlocks.join('\n\n'),
    '}',
    '',
  ].join('\n'),
);

const config = await prettier.resolveConfig(SCOPED_CSS);
for (const [path, source] of files)
  files.set(
    path,
    await prettier.format(source, { ...config, parser: 'css', filepath: path }),
  );

const expected = new Set([...files.keys()].map((p) => resolve(p)));
const existing = new Set(
  (await readdir(THEMES_DIR).catch(() => [])).map((f) =>
    resolve(THEMES_DIR, f),
  ),
);
const stray = [...existing].filter((p) => !expected.has(p));

if (check) {
  const stale = [];
  for (const [path, source] of files) {
    const current = await readFile(path, 'utf8').catch(() => null);
    if (current !== source) stale.push(path);
  }
  if (stale.length || stray.length) {
    for (const path of stale) console.error(`  stale: ${path}`);
    for (const path of stray) console.error(`  stray: ${path}`);
    fail(
      'preset themes are out of date with the @manti-ui/tokens contract.\n' +
        'Run `pnpm gen:presets` and commit the result.',
    );
  }
  console.log(`preset themes are in sync (${entries.length} presets).`);
} else {
  await mkdir(THEMES_DIR, { recursive: true });
  for (const path of stray) await rm(path);
  for (const [path, source] of files) await writeFile(path, source);
  console.log(`gen-preset-css: wrote ${files.size} stylesheets.`);
}
