/**
 * Generate the Google Fonts catalogue the font picker offers.
 *
 *   node scripts/gen-google-fonts.mjs           # rewrite the list
 *   node scripts/gen-google-fonts.mjs --check   # fail if it is stale
 *
 * The list is committed rather than fetched at runtime on purpose. Google's
 * catalogue endpoint is not part of the documented API, the app's CSP keeps
 * `connect-src` on 'self', and a font picker that cannot open without a network
 * round trip is worse than one that is a release behind. Re-run it whenever the
 * catalogue is worth refreshing.
 *
 * Only the name and a fallback generic are kept: the CSS2 endpoint ignores
 * weights a family does not have (it answers 200 with whatever exists), so one
 * fixed `wght@400;500;600;700` request works for every family and no per-family
 * weight table is needed.
 *
 * The output is one `name|generic` string rather than an array of objects. An
 * AST ~1,950 object literals wide overflows Babel's stack when Storybook's
 * react-docgen walks the module graph; a string literal is a single node.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/data/google-fonts.ts');
const SOURCE = 'https://fonts.google.com/metadata/fonts';
const check = process.argv.includes('--check');

/** Google's own categories, mapped to the CSS generic each one falls back to. */
const GENERIC = {
  'Sans Serif': 'sans-serif',
  Serif: 'serif',
  Display: 'sans-serif',
  Handwriting: 'cursive',
  Monospace: 'monospace',
};

const response = await fetch(SOURCE);
if (!response.ok) {
  console.error(`gen-google-fonts: ${SOURCE} answered ${response.status}`);
  process.exit(1);
}

const { familyMetadataList: families } = await response.json();
const catalogue = families
  // Popularity first: the head of the list is what a visitor is looking for,
  // and the combobox filters the tail by name anyway.
  .slice()
  .sort((a, b) => a.popularity - b.popularity)
  .map((family) => ({
    name: family.family,
    generic: GENERIC[family.category] ?? 'sans-serif',
  }));

const rows = catalogue.map((font) => `${font.name}|${font.generic}`).join('\n');

/** A single-quoted JS string literal, the form Prettier leaves alone here. */
function singleQuoted(value) {
  const body = JSON.stringify(value)
    .slice(1, -1)
    .replaceAll('\\"', '"')
    .replaceAll("'", "\\'");
  return `'${body}'`;
}
const source = `/**
 * Generated by scripts/gen-google-fonts.mjs. DO NOT EDIT.
 *
 * One string rather than a JSON array of ~1,950 objects: an AST that wide
 * overflows Babel's stack when Storybook's react-docgen walks the module
 * graph, and a string literal is a single node. \`googleFonts.ts\` splits it.
 * Rows are \`name|generic\`, most popular first.
 */
export default ${singleQuoted(rows)};
`;

if (check) {
  const current = await readFile(OUT, 'utf8').catch(() => null);
  if (current !== source) {
    console.error(
      'gen-google-fonts: the catalogue is out of date.\n' +
        'Run `pnpm gen:fonts` and commit the result.',
    );
    process.exit(1);
  }
  console.log(
    `google fonts catalogue is in sync (${catalogue.length} families).`,
  );
} else {
  await writeFile(OUT, source);
  console.log(`gen-google-fonts: wrote ${catalogue.length} families.`);
}
